#!/usr/bin/env node
// npm から取得したフォント／アイコンのうち、必要なファイルだけを design/assets/ にコピーする。
//
// 使い方:
//   mkdir /tmp/dl && cd /tmp/dl && npm init -y && \
//     npm i @fontsource/noto-serif-jp @fontsource/zen-old-mincho @fontsource/noto-sans-jp lucide-static
//   node design/tools/copy-assets.js /tmp/dl/node_modules
//
// 出力:
//   design/assets/fonts/<family>/files/*.woff2   (woff2 のみ。woff は不要なので省く)
//   design/assets/fonts/<family>/<family>-<weight>.css
//   design/assets/fonts/fonts.css                 (全部をまとめて読む CSS)
//   design/assets/fonts/<family>/LICENSE
//   design/assets/icons/lucide-icons.js           (window.LUCIDE_ICONS = {name: "<svg内側>"})
//   design/assets/icons/LICENSE
const fs = require('fs');
const path = require('path');

const nm = process.argv[2];
if (!nm || !fs.existsSync(nm)) {
  console.error('usage: node copy-assets.js <node_modules dir>');
  process.exit(1);
}
const ASSETS = path.resolve(__dirname, '..', 'assets');

// 使うウェイトだけ（増やすときはここに追記）
const FONTS = {
  'noto-serif-jp': [500, 700, 900], // 見出し（標準）
  'zen-old-mincho': [700, 900],     // 見出し（代替: ?font=zen）
  'noto-sans-jp': [400, 500],       // 本文・キャプション
};

const cssAll = [];
for (const [fam, weights] of Object.entries(FONTS)) {
  const src = path.join(nm, '@fontsource', fam);
  const dst = path.join(ASSETS, 'fonts', fam);
  fs.mkdirSync(path.join(dst, 'files'), { recursive: true });
  fs.copyFileSync(path.join(src, 'LICENSE'), path.join(dst, 'LICENSE'));
  for (const w of weights) {
    let css = fs.readFileSync(path.join(src, `${w}.css`), 'utf8');
    // woff フォールバックを削除し、woff2 だけ参照する
    css = css.replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '');
    css = css.replace(/font-display:\s*swap;/g, 'font-display: block;');
    const files = [...css.matchAll(/url\(\.\/files\/([^)]+\.woff2)\)/g)].map((m) => m[1]);
    for (const f of files) fs.copyFileSync(path.join(src, 'files', f), path.join(dst, 'files', f));
    const name = `${fam}-${w}.css`;
    fs.writeFileSync(path.join(dst, name), css);
    cssAll.push(`@import url("./${fam}/${name}");`);
    console.log(`font ${fam} ${w}: ${files.length} files`);
  }
}
fs.writeFileSync(path.join(ASSETS, 'fonts', 'fonts.css'), cssAll.join('\n') + '\n');

// Lucide: SVG ファイルの中身（path 等）だけを JS に束ねる。
// file:// でも fetch 不要で読めるように <script> で読み込む形式にする。
const lsrc = path.join(nm, 'lucide-static');
const ldst = path.join(ASSETS, 'icons');
fs.mkdirSync(ldst, { recursive: true });
fs.copyFileSync(path.join(lsrc, 'LICENSE'), path.join(ldst, 'LICENSE'));
const version = JSON.parse(fs.readFileSync(path.join(lsrc, 'package.json'), 'utf8')).version;
const icons = {};
for (const f of fs.readdirSync(path.join(lsrc, 'icons')).sort()) {
  if (!f.endsWith('.svg')) continue;
  const svg = fs.readFileSync(path.join(lsrc, 'icons', f), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  icons[f.slice(0, -4)] = inner.replace(/\s*\n\s*/g, '').trim();
}
fs.writeFileSync(
  path.join(ldst, 'lucide-icons.js'),
  `/* lucide-static v${version} (ISC License, see LICENSE) - generated by design/tools/copy-assets.js */\n` +
    `window.LUCIDE_ICONS=${JSON.stringify(icons)};\n`
);
console.log(`lucide ${version}: ${Object.keys(icons).length} icons`);
